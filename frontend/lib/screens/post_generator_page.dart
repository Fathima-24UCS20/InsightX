List<String> get campaignDays {
  final campaign = selectedCampaign;

  if (campaign == null ||
      campaign.startDate == null ||
      campaign.endDate == null) {
    return [];
  }

  final totalDays =
      campaign.endDate!.difference(
        campaign.startDate!,
      ).inDays +
      1;

  return List.generate(
    totalDays,
    (index) => 'Day ${index + 1}',
  );
}

