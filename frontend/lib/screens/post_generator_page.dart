bool isLoadingCampaign = true;
String? campaignError;

late CampaignService campaignService;
late SocialPostService socialPostService;

SocialPost? generatedPost;

bool isGeneratingPost = false;
String? postGenerationError;

Timer? _postRefreshTimer;
bool _isLoadingSavedPost = false;


String _getImageUrl(String imageUrl) {
  if (imageUrl.startsWith('http://') ||
      imageUrl.startsWith('https://')) {
    return imageUrl;
  }

  return 'http://127.0.0.1:8000$imageUrl';
}


@override
void initState() {
  super.initState();

  campaignService = CampaignService(
    baseUrl: 'http://127.0.0.1:8000',
  );

  socialPostService = SocialPostService(
    baseUrl: 'http://127.0.0.1:8000',
  );

  _loadCampaign();

  // Keep checking the backend so a post generated by the scheduler
  // appears while this page is already open.
  _postRefreshTimer = Timer.periodic(
    const Duration(seconds: 15),
    (_) => _loadSavedPost(silent: true),
  );
}

@override
void dispose() {
  _postRefreshTimer?.cancel();
  socialPostService.dispose();
  super.dispose();
}



Future<void> _loadCampaign() async {
  try {
    setState(() {
      isLoadingCampaign = true;
      campaignError = null;
    });

    final campaigns = await campaignService.fetchSavedCampaigns();

    if (!mounted) return;

    if (campaigns.isEmpty) {
      setState(() {
        isLoadingCampaign = false;
        campaignError = 'No saved campaigns found.';
      });
      return;
    }

    setState(() {
      selectedCampaign = campaigns.first;
      isLoadingCampaign = false;
    });

    await _loadSavedPost();
  } catch (e) {
    if (!mounted) return;

    setState(() {
      isLoadingCampaign = false;
      campaignError = e.toString();
    });
  }
}

Future<void> _loadSavedPost({
  bool silent = false,
}) async {
  final campaign = selectedCampaign;

  if (campaign == null || campaign.id == null) {
    return;
  }

  final platforms = campaign.channels;

  if (platforms.isEmpty ||
      selectedDay >= campaignDays.length ||
      selectedPlatform >= platforms.length) {
    return;
  }

  if (_isLoadingSavedPost) {
    return;
  }

  _isLoadingSavedPost = true;

  try {
    final posts = await socialPostService.fetchPosts(
      campaignId: campaign.id!,
      dayNumber: selectedDay + 1,
      platform: platforms[selectedPlatform].key,
    );

    if (!mounted) return;

    // The scheduler stores the completed post in PostgreSQL.
    // Pick the newest matching post and show it in the same preview
    // used by manual generation.
    if (posts.isNotEmpty) {
      final post = posts.first;

      setState(() {
        generatedPost = post;
        postGenerationError = null;
      });

      if (!silent) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text(
              'Saved generated post loaded successfully.',
            ),
            duration: Duration(seconds: 2),
          ),
        );
      }
    }
  } catch (e) {
    // Do not show a polling error every 15 seconds.
    // Manual generation and the rest of the page remain usable.
    if (!silent && mounted) {
      setState(() {
        postGenerationError = e.toString();
      });
    }
  } finally {
    _isLoadingSavedPost = false;
  }
}

Future<void> _generatePost() async {
  if (selectedCampaign == null ||
      selectedCampaign!.id == null) {
    return;
  }

  if (selectedCampaign!.channels.isEmpty) {
    setState(() {
      postGenerationError = 'No platform selected for this campaign.';
    });
    return;
  }

  if (selectedPlatform >= selectedCampaign!.channels.length) {
    setState(() {
      postGenerationError = 'Invalid platform selected.';
    });
    return;
  }

  setState(() {
    isGeneratingPost = true;
    postGenerationError = null;
  });

  try {
    final post = await socialPostService.generatePost(
      campaignId: selectedCampaign!.id!,
      dayNumber: selectedDay + 1,
      platform: selectedCampaign!
          .channels[selectedPlatform]
          .key,
    );

    if (!mounted) return;

    setState(() {
      generatedPost = post;
      isGeneratingPost = false;
    });
  } catch (e) {
    if (!mounted) return;

    setState(() {
      isGeneratingPost = false;
      postGenerationError = e.toString();
    });
  }
}

int get _campaignDays {
  if (selectedCampaign == null ||
      selectedCampaign!.startDate == null ||
      selectedCampaign!.endDate == null) {
    return 0;
  }

  return selectedCampaign!.endDate!
          .difference(selectedCampaign!.startDate!)
          .inDays +
      1;
}

Future<void> _showSavedCampaigns() async {
  try {
    setState(() {
      isLoadingCampaign = true;
      campaignError = null;
    });

    final campaigns =
        await campaignService.fetchSavedCampaigns();

    if (!mounted) return;

    setState(() {
      isLoadingCampaign = false;
    });

    if (campaigns.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('No saved campaigns found.'),
        ),
      );
      return;
    }

    final Campaign? selected = await showDialog<Campaign>(
      context: context,
      builder: (dialogContext) {
        return _SavedCampaignsDialog(
          campaigns: campaigns,
        );
      },
    );

    if (selected == null || !mounted) return;

    setState(() {
      selectedCampaign = selected;

      // Reset selections for the newly selected campaign.
      selectedDay = 0;
      selectedPlatform = 0;

      generatedPost = null;
      postGenerationError = null;
    });

    await _loadSavedPost();
  } catch (e) {
    if (!mounted) return;

    setState(() {
      isLoadingCampaign = false;
      campaignError = e.toString();
    });
  }
}

