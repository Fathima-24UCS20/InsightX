// ----------------------------------------------------------

Future<void> _downloadPost() async {
  if (generatedPost == null || generatedPost!.imageUrl == null) {
    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('No generated post image available.'),
      ),
    );
    return;
  }

  try {
    final imageUrl = _getImageUrl(generatedPost!.imageUrl!);

    final response = await http.get(Uri.parse(imageUrl));

    if (response.statusCode != 200) {
      throw Exception(
        'Failed to download image: ${response.statusCode}',
      );
    }

    final bytes = Uint8List.fromList(response.bodyBytes);

    final blob = html.Blob(
      [bytes],
      'image/png',
    );

    final url = html.Url.createObjectUrlFromBlob(blob);

    final anchor = html.AnchorElement(href: url)
      ..setAttribute(
        'download',
        'insightx_${selectedCampaign?.name ?? 'post'}_day${selectedDay + 1}.png',
      )
      ..style.display = 'none';

    html.document.body?.children.add(anchor);
    anchor.click();
    anchor.remove();

    html.Url.revokeObjectUrl(url);

    if (!mounted) return;

    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('Post downloaded successfully.'),
      ),
    );
  } catch (e) {
    if (!mounted) return;

    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text('Download failed: $e'),
      ),
    );
  }
}


